def ensure_workspace(path: Path) -> None:
    if not str(path.resolve()).startswith(str(REPO_ROOT.resolve())):
        raise ValueError(f"All artifacts must stay in Movie3R workspace: {path}")


def image_paths(data_root: Path, camera: str, frames: list[int]) -> list[Path]:
    paths = [data_root / f"exo/{camera}/images/{int(frame):05d}.jpg" for frame in frames]
    missing = next((path for path in paths if not path.is_file()), None)
    if missing is not None:
        raise FileNotFoundError(missing)
    return paths


def case_path(b0_dir: Path, chain_index: int, cut_index: int, chains: list[dict[str, Any]]) -> Path:
    shots = chains[chain_index]["shots"]
    return b0_dir / "cases" / (
        f"chain{chain_index}_cut{cut_index}_{shots[cut_index]['camera']}_{shots[cut_index + 1]['camera']}.json"
    )


def load_b0_cases(
    b0_dir: Path, chains: list[dict[str, Any]], checkpoint_sha: str, manifest_sha: str
) -> list[list[np.ndarray]]:
    index_path = b0_dir / "index.json"
    index = json.loads(index_path.read_text(encoding="utf-8"))
    if str(index["checkpoint"]["sha256"]) != checkpoint_sha:
        raise ValueError("B0 cache checkpoint hash does not match the requested raw geometry checkpoint")
    if str(index["manifest"]["sha256"]) != manifest_sha:
        raise ValueError("B0 cache manifest hash does not match the requested confirmation manifest")
    if bool(index["execution"].get("da3_used", True)):
        raise ValueError("This confirmation protocol forbids DA3 B0 artifacts")
    if bool(index["runtime_contract"].get("shadow_state_committed", True)):
        raise ValueError("B0 cache violates shadow-state transaction contract")
    output: list[list[np.ndarray]] = []
    for chain_index in range(len(chains)):
        boundaries = []
        for cut_index in (0, 1):
            source = case_path(b0_dir, chain_index, cut_index, chains)
            row = json.loads(source.read_text(encoding="utf-8"))
            audit = row["runtime_input_audit"]
            if int(audit["future_post_frames_used"]) != 0 or bool(audit["gt_used"]):
                raise ValueError(f"invalid causal/GT audit in {source}")
            if bool(audit["shadow_state_committed"]):
                raise ValueError(f"shadow state committed in {source}")
            replay = float(row["camera_replay"]["max_abs_difference"])
            if replay > 1e-5:
                raise ValueError(f"B0 camera replay failed in {source}: {replay}")
            boundary = np.asarray(row["boundaries"]["b0"], dtype=np.float64)
            if boundary.shape != (4, 4) or not np.isfinite(boundary).all():
                raise ValueError(f"invalid B0 matrix in {source}")
            boundaries.append(boundary)
        output.append(boundaries)
    return output


def build_geometry_cache(
    args: argparse.Namespace,
    chains: list[dict[str, Any]],
    b0_boundaries: list[list[np.ndarray]],
    destination: Path,
) -> dict[str, Any]:
    """Run clean raw-reset Human3R once per shot and save compact geometry."""
    if str(args.device) != "cpu":
        raise ValueError("The confirmation geometry cache is deliberately CPU-only")
    torch.manual_seed(int(args.seed))
    np.random.seed(int(args.seed))
    started = time.perf_counter()
    model = ARCroco3DStereo.from_pretrained(str(args.model_path)).to("cpu")
    flags = configure_model(model)
    layer = SMPL_Layer(
        type="smplx", gender="neutral", num_betas=10, kid=False, person_center="head"
    ).to("cpu").eval()
    cached_chains = []
    try:
        for chain_index, chain in enumerate(chains):
            segments = []
            for segment_index, shot in enumerate(chain["shots"]):
                frames = [int(value) for value in shot["frames"]]
                camera = str(shot["camera"])
                views = set_event_indices(
                    prepare_full_square_input(
                        model, image_paths(args.data_root, camera, frames), SimpleNamespace(size=int(args.size))
                    ),
                    set(),
                )
                predictions, returned, debug, seconds = run_rollout(
                    model, views, "cpu", f"b0_ego_chain{chain_index}_segment{segment_index}_raw_reset_cpu"
                )
                # GT enters here only after the raw forward has completed.  These labels
                # remain evaluator metadata; anonymous_assignment never consumes them.
                labels, assignments = assign_identities(
                    args.data_root, [camera] * len(frames), frames, returned, debug,
                    int(args.size), float(args.assignment_threshold_px)
                )
                frame_rows = []
                for frame, prediction, view, token, frame_labels in zip(
                    frames, predictions, returned, debug, labels
                ):
                    # Cross96 was trained with max_humans=1 and may emit no
                    # human head at a difficult frame.  Treat this as a real
                    # miss, not as an evaluator crash or a reason to remove
                    # the frame from the frozen confirmation stream.
                    missing_human_head = "smpl_transl" not in prediction
                    humans = [] if missing_human_head else layer_humans(prediction, view, token, layer)
                    if len(humans) != len(frame_labels):
                        raise ValueError(
                            f"human/GT-detection count mismatch chain={chain_index} segment={segment_index} frame={frame}"
                        )
                    frame_rows.append(
                        {
                            "camera_name": camera,
                            "dataset_frame": int(frame),
                            "camera_c2w": camera_matrix(prediction).astype(np.float64),
                            "missing_human_head": bool(missing_human_head),
                            "people": [
                                compact_person(human, prediction, int(frame_labels[index]))
                                for index, human in enumerate(humans)
                            ],
                        }
                    )
                segments.append(
                    {
                        "camera_name": camera,
                        "dataset_frames": frames,
                        "inference_seconds": float(seconds),
                        "assignment_evaluator_only": assignments,
                        "frames": frame_rows,
                    }
                )
                print(
                    f">> cached chain={chain_index} segment={segment_index} "
                    f"people={sum(len(row['people']) for row in frame_rows)}",
                    flush=True,
                )
                del predictions, returned, debug, views
            cached_chains.append(
                {
                    "chain_index": int(chain_index),
                    "chain_id": str(chain.get("id", chain_index)),
                    "segments": segments,
                    "b0_boundaries": b0_boundaries[chain_index],
                    "b0_case_reports": [
                        str(case_path(args.b0_dir, chain_index, cut_index, chains))
                        for cut_index in (0, 1)
                    ],
                }
            )
    finally:
        del layer, model
    cache = {
        "protocol": {
            "checkpoint": str(args.model_path),
            "device": "cpu",
            "same_forward_for_all_methods": True,
            "raw_branch": "clean hard reset independently for each shot; correction event disabled",
            "b0_source": "causal RGB-only cut-first B0 cache",
            "gt_use": "detection/identity assignment and metric evaluation only after raw model action",
            "model_flags": flags,
        },
        "chains": cached_chains,
        "wall_seconds": time.perf_counter() - started,
    }
    destination.parent.mkdir(parents=True, exist_ok=True)
    torch.save(cache, destination)
    print(f">> wrote geometry cache {destination}", flush=True)
    return cache


def method_chains_core(cache: dict[str, Any]) -> tuple[dict[str, list[dict]], list[dict]]:
    """Compose B0 and apply only frozen BRTC-LC, preserving exact fallback."""
    methods = {name: [] for name in ("raw_reset", "b0", "b0_brtc_lc")}
    boundary_debug = []
    for source_chain in cache["chains"]:
        if len(source_chain["segments"]) != 3 or len(source_chain["b0_boundaries"]) != 2:
            raise ValueError("This confirmation evaluator requires exactly three shots/two cuts")
        raw_segments = []
        for segment_index, segment in enumerate(source_chain["segments"]):
            frames = copy.deepcopy(segment["frames"])
            for frame in frames:
                frame["method_camera_c2w"] = np.asarray(frame["camera_c2w"], dtype=np.float64)
                for person in frame["people"]:
                    person["global_track_id"] = segment_index * 1000 + int(person["native_track_id"])
            raw_segments.append(frames)

        b0_segments, associations = [], []
        cumulative = np.eye(4, dtype=np.float64)
        next_track = 0
        previous_last_by_track: dict[int, dict[str, Any]] = {}
        for segment_index, segment in enumerate(source_chain["segments"]):
            if segment_index:
                cumulative = cumulative @ np.asarray(
                    source_chain["b0_boundaries"][segment_index - 1], dtype=np.float64
                )
            frames = []
            for source_frame in segment["frames"]:
                frame = copy.deepcopy(source_frame)
                frame["method_camera_c2w"] = cumulative @ np.asarray(
                    source_frame["camera_c2w"], dtype=np.float64
                )
                frame["people"] = [transform_person(cumulative, person) for person in source_frame["people"]]
                frames.append(frame)
            if segment_index == 0:
                native_to_global: dict[int, int] = {}
                next_track = assign_segment_tracks(frames, native_to_global, next_track)
                association = None
            else:
                association = anonymous_assignment(previous_last_by_track, frames[0]["people"])
                native_to_global = {
                    int(frames[0]["people"][post_index]["native_track_id"]): int(track)
                    for track, post_index in association["track_to_post_index"].items()
                }
                next_track = assign_segment_tracks(frames, native_to_global, next_track)
            previous_last_by_track = {
                int(person["global_track_id"]): person for person in frames[-1]["people"]
            }
            b0_segments.append(frames)
            associations.append(association)

        brtc_segments = [copy.deepcopy(b0_segments[0])]
        for segment_index in (1, 2):
            post_frames = copy.deepcopy(b0_segments[segment_index])
            pre_frame = brtc_segments[-1][-1]
            pre_by_track = {int(person["global_track_id"]): person for person in pre_frame["people"]}
            b0_pre_by_track = {
                int(person["global_track_id"]): person
                for person in b0_segments[segment_index - 1][-1]["people"]
            }
            association = associations[segment_index]
            track_post_pairs = sorted(association["track_to_post_index"].items())
            pre_people = [pre_by_track[int(track)] for track, _ in track_post_pairs]
            matches = [(index, int(post)) for index, (_, post) in enumerate(track_post_pairs)]
            post_people = post_frames[0]["people"]
            corrected_first, debug = refine_matched_people(
                np.asarray(pre_frame["method_camera_c2w"], dtype=np.float64),
                np.asarray(post_frames[0]["method_camera_c2w"], dtype=np.float64),
                pre_people, post_people, matches, BRTC_CONFIG,
            )
            if debug.get("camera_update") != "none":
                raise RuntimeError("BRTC attempted to edit the camera")
            if int(debug.get("matched_count", -1)) != len(matches):
                raise RuntimeError("BRTC returned inconsistent matched_count")
            matched_post = {post for _, post in matches}
            shifts: dict[int, np.ndarray] = {}
            unmatched_max_abs_change = 0.0
            for post_index, (before, after) in enumerate(zip(post_people, corrected_first)):
                shift = np.asarray(after["root"], dtype=np.float64) - np.asarray(before["root"], dtype=np.float64)
                if post_index not in matched_post:
                    unmatched_max_abs_change = max(unmatched_max_abs_change, float(np.max(np.abs(shift))))
                shifts[int(before["native_track_id"])] = shift
            if unmatched_max_abs_change > 1e-12:
                raise RuntimeError("BRTC modified an unmatched post person")
            for frame in post_frames:
                frame["people"] = [
                    shift_person(person, shifts.get(int(person["native_track_id"]), np.zeros(3)))
                    for person in frame["people"]
                ]
            boundary_debug.append(
                {
                    "chain_index": int(source_chain["chain_index"]),
                    "chain_id": source_chain.get("chain_id"),
                    "cut_index": segment_index - 1,
                    "association": association,
                    "brtc_runtime_module": refine_matched_people.__module__,
                    "brtc": debug,
                    "shift_by_native_track": shifts,
                    "unmatched_max_abs_change": unmatched_max_abs_change,
                    "pre_inherited_brtc_shift_by_global_track": {
                        int(track): np.asarray(person["root"], dtype=np.float64)
                        - np.asarray(b0_pre_by_track[track]["root"], dtype=np.float64)
                        for track, person in pre_by_track.items()
                        if track in b0_pre_by_track
                    },
                }
            )
            brtc_segments.append(post_frames)

        for name, segments in (
            ("raw_reset", raw_segments),
            ("b0", b0_segments),
            ("b0_brtc_lc", brtc_segments),
        ):
            methods[name].append(
                {
                    "chain_index": int(source_chain["chain_index"]),
                    "chain_id": source_chain.get("chain_id"),
                    "segments": segments,
                    "frames": [frame for segment in segments for frame in segment],
                }
            )
    return methods, boundary_debug


def paired_chain_bootstrap(
    reports: dict[str, list[dict[str, Any]]], seed: int, samples: int = 10000
) -> dict[str, Any]:
    """Small-N confidence interval over independently selected Ego temporal chains."""
    generator = np.random.default_rng(seed)
    output = {}
    for metric in ("w_mpjpe_mm", "wa_mpjpe_mm", "fixed_world_root_mm", "fixed_world_joint_mm"):
        b0 = np.asarray([row["metrics"][metric] for row in reports["b0"]], dtype=np.float64)
        brtc = np.asarray([row["metrics"][metric] for row in reports["b0_brtc_lc"]], dtype=np.float64)
        delta = brtc - b0
        draws = np.mean(delta[generator.integers(0, len(delta), size=(samples, len(delta)))], axis=1)
        output[metric] = {
            "paired_delta_brtc_minus_b0_mm": float(delta.mean()),
            "bootstrap_95pct_ci_mm": [float(np.quantile(draws, 0.025)), float(np.quantile(draws, 0.975))],
            "chain_count": int(len(delta)),
        }
    return output


def main() -> None:
    args = parse_args()
    for path in (args.manifest, args.b0_dir, args.output_dir):
        ensure_workspace(path)
    if not args.model_path.is_file():
        raise FileNotFoundError(args.model_path)
    manifest = load_manifest(args.manifest)
    chains = manifest["chains"]
    checkpoint_hash, manifest_hash = checkpoint_sha256(args.model_path), sha256(args.manifest)
    b0_boundaries = load_b0_cases(args.b0_dir, chains, checkpoint_hash, manifest_hash)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    cache_path = args.geometry_cache or args.output_dir / "raw_geometry_cpu.pt"
    ensure_workspace(cache_path)
    if args.overwrite_cache or (args.build_cache and not cache_path.is_file()):
        cache = build_geometry_cache(args, chains, b0_boundaries, cache_path)
    elif cache_path.is_file():
        cache = torch.load(cache_path, map_location="cpu", weights_only=False)
        if str(cache["protocol"]["checkpoint"]) != str(args.model_path):
            raise ValueError("geometry cache checkpoint does not match requested B0 checkpoint")
    else:
        raise FileNotFoundError(f"Missing geometry cache {cache_path}; run with --build-cache")

    methods, boundary_debug = method_chains_core(cache)
    _, exo = load_colmap(args.data_root)
    vertex_map, joint_regressor = load_smpl_resources()
    method_reports: dict[str, dict[str, Any]] = {}
    chain_reports: dict[str, list[dict[str, Any]]] = {}
    method_roots: dict[str, list[dict[tuple[int, str], float]]] = {}
    for name, chains_for_method in methods.items():
        rows, arrays, roots = [], [], []
        for chain in chains_for_method:
            row, raw_arrays, root_errors = evaluate_chain(
                chain, args.data_root, exo, vertex_map, joint_regressor, float(args.fps)
            )
            rows.append(row)
            arrays.append(raw_arrays)
            roots.append(root_errors)
        method_reports[name] = aggregate_method(rows, arrays)
        chain_reports[name] = rows
        method_roots[name] = roots
    camera_exactness = camera_exactness_audit(methods["b0"], methods["b0_brtc_lc"])
    if not camera_exactness["bit_exact"]:
        raise RuntimeError(f"BRTC changed B0 camera: {camera_exactness}")
    harms = harm_audit(method_roots["b0"], method_roots["b0_brtc_lc"])
    causal = boundary_causal_audit(boundary_debug)
    unmatched_max_abs = float(max((row["unmatched_max_abs_change"] for row in boundary_debug), default=0.0))
    accepted = sum(int(row["brtc"]["accepted_count"]) for row in boundary_debug)
    matched = sum(int(row["brtc"]["matched_count"]) for row in boundary_debug)
    report = {
        "title": "Frozen cut-first B0 + frozen BRTC-LC EgoHumans confirmation",
        "decision_scope": "confirmation only; no threshold, checkpoint, or refinement policy was selected from this manifest",
        "execution": {
            "geometry_device": "cpu",
            "b0_generation_device": json.loads((args.b0_dir / "index.json").read_text(encoding="utf-8"))["execution"]["device"],
            "da3_used": False,
            "external_pretrained_models": [],
            "checkpoint": str(args.model_path),
            "checkpoint_sha256": checkpoint_hash,
            "manifest": str(args.manifest),
            "manifest_sha256": manifest_hash,
            "geometry_cache": str(cache_path),
        },
        "runtime_contract": {
            "clean_state": "raw reset state is the only model state represented by each post-cut shot",
            "shadow": "the correction shadow is read-only and only its camera-derived B0 is retained",
            "b0": "one cached 4x4 boundary per cut, composed G0=I; G1=B01; G2=B01@B12",
            "brtc": "anonymous B0-aligned geometry association; frozen ray/layout translation; rejected and unmatched people exact B0",
            "camera": "BRTC never edits camera",
            "future_post_frames_for_action": 0,
            "gt_runtime": False,
        },
        "protocol": {
            "dataset": manifest["dataset"],
            "chain_count": len(chains),
            "cut_count": len(chains) * 2,
            "raw_frame_count": sum(len(shot["frames"]) for chain in chains for shot in chain["shots"]),
            "official_multithumbs_protocol": False,
            "metric_note": "local transparent Multi-THuMBS-style evaluator; not an official Multi-THuMBS reproduction",
            "gt_usage": "2D detection labels and 3D metrics only after B0/BRTC actions",
        },
        "methods": method_reports,
        "per_chain": chain_reports,
        "paired_chain_bootstrap": paired_chain_bootstrap(chain_reports, int(args.seed)),
        "camera_exactness": camera_exactness,
        "b0_to_brtc_harm": harms,
        "boundary_causal_audit": causal,
        "brtc_runtime_audit": {
            "matched_people": matched,
            "accepted_people": accepted,
            "acceptance": float(accepted / max(matched, 1)),
            "unmatched_max_abs_change": unmatched_max_abs,
            "camera_bit_exact": bool(camera_exactness["bit_exact"]),
        },
        "boundary_runtime_debug": boundary_debug,
        "limitations": [
            "EgoHumans 001_legoassemble is one held-out capture, not the official unpublished Multi-THuMBS split.",
            "Each synthetic cut repeats a physical timestamp from two synchronized exo cameras; it is a controlled cross-camera cut rather than editorial video footage.",
            "The B0 checkpoint may be trained with max_humans=1; this evaluation tests multi-person inference/generalization but is not itself multi-person identity training.",
            "Kabsch is deliberately excluded because its strict policy status is qualified rather than promoted; it must not be selected on confirmation data.",
        ],
    }
    destination = args.output_dir / "report.json"
    destination.write_text(
        json.dumps(jsonable(report), indent=2, ensure_ascii=False, allow_nan=False) + "\n",
        encoding="utf-8",
    )
    print(
        json.dumps(
            {
                "report": str(destination),
                "b0_w": method_reports["b0"]["metrics"]["w_mpjpe_mm"],
                "brtc_w": method_reports["b0_brtc_lc"]["metrics"]["w_mpjpe_mm"],
                "b0_wa": method_reports["b0"]["metrics"]["wa_mpjpe_mm"],
                "brtc_wa": method_reports["b0_brtc_lc"]["metrics"]["wa_mpjpe_mm"],
                "camera_bit_exact": camera_exactness["bit_exact"],
            },
            indent=2,
        ),
        flush=True,
    )


if __name__ == "__main__":
    main()
