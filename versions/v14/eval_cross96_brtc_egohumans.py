#!/usr/bin/env python3
"""Evaluate a frozen cut-first B0 + frozen BRTC-LC on an EgoHumans manifest.

The only runtime inputs are RGB and the pre-registered three-shot chains.  A
separate B0 cache, generated by :mod:`generate_cross96_b0_egohumans`, contains
one causal first-post-cut B0 per boundary.  This evaluator then runs three
independent clean raw-reset shots, composes the cached B0 matrices causally,
and applies the frozen BRTC-LC translation only after anonymous B0-aligned
matching.  GT labels, cameras, and SMPL meshes are loaded *after* all B0 and
BRTC actions have been completed and are evaluator-only.

It intentionally evaluates only the established B0+BRTC mainline.  The
strictly qualified Kabsch candidate and all No-Go variants are not silently
reselected on this confirmation split.
"""

